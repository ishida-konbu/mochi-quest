const castByName = new Map(CAST.map(person => [person.name, person]));

function entry(kind, id, speaker, prop, title, action, text, note, options = {}) {
  const resident = castByName.get(speaker);
  return { id, characterId: resident?.id ?? null, speaker, region: resident?.region, prop, kind, title, action, text, note, requires: [], ...options };
}
const look = (...args) => entry('観察', ...args);
const hear = (...args) => entry('証言', ...args);

