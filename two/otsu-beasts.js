// Old delivery IDs retain their original local axes, pivots and journal framing.
const models=new Map();
export function otsuParts(type){
  if(models.has(type))return models.get(type);
  const parts=[];
  const add=(name,pivot,draw)=>parts.push(piece(name,pivot,draw));
  if(type==='elephant'){
    add('body',zero,elephantBody);add('head',[0,1.51,.80],elephantHead);add('trunk',[0,1.61,1.307],elephantTrunk);
    for(const s of sides)add('ear'+s,[s*.331,1.824,.951],f=>elephantEar(f,s));
  }else if(type==='ox'){
    add('body',zero,oxBody);add('head',oxHeadPivot,oxHead);
  }else if(type==='baku'){
    add('body',zero,bakuBody);add('head',[0,1.19,.56],bakuHead);
  }else if(type==='horse'){
    add('body',zero,horseBody);add('head',[0,1.81,.70],horseHead);add('tail',[0,1.54,-.969],horseTail);
  }else throw new Error('Unknown scroll quadruped '+type);
  for(const s of sides)for(const d of sides){
    const front=d===1,name='leg'+s+','+d;
    if(type==='elephant')add(name,[s*.36,.963,front?.56:-.72],f=>elephantLeg(f,s,d));
    else if(type==='baku')add(name,[s*.248,.79,front?.41:-.555],f=>bakuLeg(f,s,d));
    else if(type==='ox')add(name,[s*.28,.8,front?.44:-.62],f=>ungulateLeg(f,s,d,false));
    else add(name,[s*.235,1.035,front?.393:-.660],f=>ungulateLeg(f,s,d,true));
  }
  models.set(type,parts);
  return parts;
}
