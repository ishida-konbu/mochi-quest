import { CAST, CHAPTERS } from './mochiyori-story.js';

const notes = new Map(CHAPTERS.flatMap(chapter => chapter.clues.map(clue => [clue.id, clue])));
const courier = '配達人のお餅';
const prop = (code, variant) => variant ? { code, variant } : { code };
const food = region => ({ code: 'food', region });
function exhibit(id, part) {
  return { code: notes.get(id).prop, variant: id, ...(part && {part}) };
}

// Indices refer to the cast and props of this one scene. A target is another object on the table.
function beat(actor, gesture, prop, caption, { partner = null, ...details } = {}) {
  return { actor, partner, gesture, prop, caption, ...details };
}
function scene(title, cast, props, beats) { return { title, cast, props, beats }; }
function clue(id, cast, props, beats) { return [id, scene(notes.get(id).action, cast, props, beats)]; }

